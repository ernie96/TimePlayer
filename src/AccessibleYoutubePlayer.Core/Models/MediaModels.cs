namespace AccessibleYoutubePlayer.Core.Models;

/// <summary>
/// Direct media stream information (audio/video or audio-only).
/// </summary>
public record StreamInfo
{
    public required string Url { get; init; }
    public string Format { get; init; } = string.Empty;
    public string Quality { get; init; } = string.Empty;
    public bool IsAudioOnly { get; init; }
    public int Bitrate { get; init; }
    public string MimeType { get; init; } = string.Empty;
    public string Codec { get; init; } = string.Empty;
    public int? Width { get; init; }
    public int? Height { get; init; }
    public int? Fps { get; init; }

    public string AccessibleLabel
    {
        get
        {
            if (IsAudioOnly)
            {
                var kbps = Bitrate > 0 ? $" {Bitrate / 1000} kbps" : string.Empty;
                return $"Audio only{kbps} ({Format})";
            }
            var res = !string.IsNullOrWhiteSpace(Quality) ? Quality : (Height.HasValue ? $"{Height}p" : "Video");
            var fpsStr = Fps.HasValue && Fps > 30 ? $" {Fps}fps" : string.Empty;
            return $"{res}{fpsStr} ({Format})";
        }
    }
}

/// <summary>
/// Represents a closed caption or subtitle track.
/// </summary>
public record SubtitleTrack
{
    public required string Language { get; init; }
    public required string LanguageName { get; init; }
    public required string Url { get; init; }
    public string MimeType { get; init; } = "text/vtt";
    public bool IsAutoGenerated { get; init; }

    public string AccessibleLabel => IsAutoGenerated
        ? $"{LanguageName} (auto-generated)"
        : LanguageName;
}

/// <summary>
/// Represents a public API instance (Piped or Invidious).
/// </summary>
public record InstanceInfo
{
    public required Uri BaseUri { get; init; }
    public string Name { get; init; } = string.Empty;
    public ProviderType ProviderType { get; init; }
    public bool IsHealthy { get; init; } = true;
    public long LatencyMs { get; init; } = -1;
    public DateTime? LastCheckedUtc { get; init; }
    public string? LastError { get; init; }

    public override string ToString() => $"{Name} ({BaseUri}) [Latency: {LatencyMs}ms, Healthy: {IsHealthy}]";
}

/// <summary>
/// Result of a search operation across backends.
/// </summary>
public record SearchResult
{
    public required IReadOnlyList<VideoMetadata> Items { get; init; }
    public string Query { get; init; } = string.Empty;
    public ProviderType ProviderUsed { get; init; }
    public string? InstanceUsed { get; init; }
    public string? NextPageToken { get; init; }
}
