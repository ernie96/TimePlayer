namespace TimePlayer.Core.Models;

/// <summary>
/// Subtitle / Closed Caption track details.
/// </summary>
public record SubtitleTrack
{
    public required string LanguageCode { get; init; }
    public required string DisplayName { get; init; }
    public required string Url { get; init; }
    public string? Format { get; init; }
    public bool IsAutoGenerated { get; init; }

    /// <summary>
    /// Gets screen reader friendly label for closed caption menu selection.
    /// </summary>
    public string AccessibleLabel =>
        IsAutoGenerated ? $"{DisplayName} (auto-generated)" : DisplayName;
}
