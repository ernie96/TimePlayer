using System.Text.Json.Serialization;

namespace TimePlayer.Core.Backends.Piped;

/// <summary>
/// Internal DTOs for Piped API responses according to official documentation.
/// Kept strictly inside the Piped backend namespace.
/// </summary>
internal sealed class PipedSearchResponse
{
    [JsonPropertyName("items")]
    public List<PipedSearchItem>? Items { get; set; }

    [JsonPropertyName("nextpage")]
    public string? NextPage { get; set; }
}

internal sealed class PipedSearchItem
{
    [JsonPropertyName("url")]
    public string? Url { get; set; }

    [JsonPropertyName("type")]
    public string? Type { get; set; }

    [JsonPropertyName("title")]
    public string? Title { get; set; }

    [JsonPropertyName("thumbnail")]
    public string? Thumbnail { get; set; }

    [JsonPropertyName("uploaderName")]
    public string? UploaderName { get; set; }

    [JsonPropertyName("uploaderUrl")]
    public string? UploaderUrl { get; set; }

    [JsonPropertyName("uploaderAvatar")]
    public string? UploaderAvatar { get; set; }

    [JsonPropertyName("uploadedDate")]
    public string? UploadedDate { get; set; }

    [JsonPropertyName("duration")]
    public long? DurationSeconds { get; set; }

    [JsonPropertyName("views")]
    public long? Views { get; set; }

    [JsonPropertyName("uploaderVerified")]
    public bool? UploaderVerified { get; set; }
}

internal sealed class PipedStreamsResponse
{
    [JsonPropertyName("title")]
    public string? Title { get; set; }

    [JsonPropertyName("description")]
    public string? Description { get; set; }

    [JsonPropertyName("uploadDate")]
    public string? UploadDate { get; set; }

    [JsonPropertyName("uploader")]
    public string? Uploader { get; set; }

    [JsonPropertyName("uploaderUrl")]
    public string? UploaderUrl { get; set; }

    [JsonPropertyName("uploaderAvatar")]
    public string? UploaderAvatar { get; set; }

    [JsonPropertyName("uploaderVerified")]
    public bool? UploaderVerified { get; set; }

    [JsonPropertyName("duration")]
    public long? Duration { get; set; }

    [JsonPropertyName("views")]
    public long? Views { get; set; }

    [JsonPropertyName("likes")]
    public long? Likes { get; set; }

    [JsonPropertyName("dislikes")]
    public long? Dislikes { get; set; }

    [JsonPropertyName("thumbnailUrl")]
    public string? ThumbnailUrl { get; set; }

    [JsonPropertyName("livestream")]
    public bool? Livestream { get; set; }

    [JsonPropertyName("hls")]
    public string? Hls { get; set; }

    [JsonPropertyName("dash")]
    public string? Dash { get; set; }

    [JsonPropertyName("audioStreams")]
    public List<PipedAudioStream>? AudioStreams { get; set; }

    [JsonPropertyName("videoStreams")]
    public List<PipedVideoStream>? VideoStreams { get; set; }

    [JsonPropertyName("subtitles")]
    public List<PipedSubtitle>? Subtitles { get; set; }

    [JsonPropertyName("relatedStreams")]
    public List<PipedSearchItem>? RelatedStreams { get; set; }
}

internal sealed class PipedAudioStream
{
    [JsonPropertyName("url")]
    public string? Url { get; set; }

    [JsonPropertyName("format")]
    public string? Format { get; set; }

    [JsonPropertyName("quality")]
    public string? Quality { get; set; }

    [JsonPropertyName("mimeType")]
    public string? MimeType { get; set; }

    [JsonPropertyName("codec")]
    public string? Codec { get; set; }

    [JsonPropertyName("bitrate")]
    public long? Bitrate { get; set; }

    [JsonPropertyName("videoOnly")]
    public bool? VideoOnly { get; set; }
}

internal sealed class PipedVideoStream
{
    [JsonPropertyName("url")]
    public string? Url { get; set; }

    [JsonPropertyName("format")]
    public string? Format { get; set; }

    [JsonPropertyName("quality")]
    public string? Quality { get; set; }

    [JsonPropertyName("mimeType")]
    public string? MimeType { get; set; }

    [JsonPropertyName("codec")]
    public string? Codec { get; set; }

    [JsonPropertyName("bitrate")]
    public long? Bitrate { get; set; }

    [JsonPropertyName("fps")]
    public int? Fps { get; set; }

    [JsonPropertyName("height")]
    public int? Height { get; set; }

    [JsonPropertyName("width")]
    public int? Width { get; set; }

    [JsonPropertyName("videoOnly")]
    public bool? VideoOnly { get; set; }
}

internal sealed class PipedSubtitle
{
    [JsonPropertyName("url")]
    public string? Url { get; set; }

    [JsonPropertyName("name")]
    public string? Name { get; set; }

    [JsonPropertyName("code")]
    public string? Code { get; set; }

    [JsonPropertyName("mimeType")]
    public string? MimeType { get; set; }

    [JsonPropertyName("autoGenerated")]
    public bool? AutoGenerated { get; set; }
}
